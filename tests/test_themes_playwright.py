"""The dark theme in Chromium, on both tiers (D148).

What only a browser says: the colours a page COMPUTES — a token that is
defined and never applied, or applied and beaten by a rule of the
framework's, reads right in every stylesheet test — and the hover box,
which plotly.js draws from the layout template under a real mouse and
nowhere else (a screenshot cannot show a hover, and the figure dict is
not the box).

The report tier is generated by `dstf compare --report` over a project
whose testing.json says `"theme": "dark"`, and read off the files.
"""

