VIEWPORT = {"width": 1280, "height": 900}
DARK = theme.DARK_THEME
LIGHT = theme.DEFAULT_THEME


def rgb(colour: str) -> str:
    """``#rrggbb`` as a browser's computed style spells it."""
    r, g, b = (int(colour[i : i + 2], 16) for i in (1, 3, 5))
    return f"rgb({r}, {g}, {b})"


#: The pixel of one point of plot ``gd``'s actual trace, from Plotly's own
#: axis objects: a hover is a real mouse move to where a point landed.
POINT_PIXEL = """
([gd, frac]) => {
  const fl = gd._fullLayout, r = gd.getBoundingClientRect();
  const tr = gd.data.find(t => (t.meta || {}).kind === 'act');
  const idx = Math.floor(tr.x.length * frac);
  return [r.left + fl.xaxis._offset + fl.xaxis.l2p(tr.x[idx]),
          r.top + fl.yaxis._offset + fl.yaxis.l2p(tr.y[idx])];
}
"""

#: The hover box as drawn. The figure's `hovermode` is `x unified`, whose
#: box is a legend-shaped group (`.hoverlayer .legend`) with one `rect.bg`
#: behind its lines — there is no `.hovertext`. Colours are the COMPUTED
#: ones: plotly.js writes them as inline styles, and a page rule could
#: still win.
HOVER_BOX = """
(gd) => {
  const layer = gd.querySelector('.hoverlayer');
  const bg = layer.querySelector('.legend .bg');
  const texts = Array.from(layer.querySelectorAll('.legend text'));
  return {
    fill: bg ? getComputedStyle(bg).fill : null,
    stroke: bg ? getComputedStyle(bg).stroke : null,
    lines: texts.map(t => [t.textContent, getComputedStyle(t).fill]),
  };
}
"""

#: What a drawn plot shows of its theme, as computed (``plot`` as resolved).
PLOT_GROUND = """
(gd) => {
  const read = (selector, property) => {
    const el = gd.querySelector(selector);
    return el ? getComputedStyle(el)[property] : null;
  };
  return {
    paper: read('.main-svg', 'backgroundColor'),
    plot: gd._fullLayout.plot_bgcolor,
    grid: read('.gridlayer path', 'stroke'),
    tick: read('.xtick text', 'fill'),
    legend: read('.legend .legendtext', 'fill'),
  };
}
"""


def assert_dark_plot(read: dict) -> None:
    assert read == {
        "paper": rgb(DARK["surface"]),
        # As plotly.js resolved it: it draws no plot-area rect where the
        # plot's ground is the paper's.
        "plot": DARK["surface"],
        "grid": rgb(DARK["border-hairline"]),
        "tick": rgb(DARK["text-secondary"]),
        "legend": rgb(DARK["text"]),
    }


def assert_dark_hover(box: dict, name: str) -> None:
    """The box is the theme's raised surface with its text, and one of its
    lines names the trace ``name``."""
    assert box["fill"] == rgb(DARK["surface-hover"]), box
    assert box["stroke"] == rgb(DARK["border"]), box
    lines = box["lines"]
    assert lines, "no hover box under the mouse"
    assert {fill for _, fill in lines} == {rgb(DARK["text"])}, lines
    assert any(re.match(rf"{re.escape(name)}\s*: ", text) for text, _ in lines), lines
    assert not any("%{" in text for text, _ in lines), lines


def _generate(tmp_path, monkeypatch, name: str):
    from dstf.cli import main

    monkeypatch.setattr("dstf.reporting.report_suite.open_in_browser", lambda p: 0)
    cfg, work = themed_project(tmp_path, name)
    main(["--config", str(cfg), "compare", "--work-dir", str(work), "--report"])
    (page,) = [
        p
        for p in work.glob("reports/*/interactive.html")
        if f"<title>{A}" in p.read_text(encoding="utf-8")
    ]
    return work / "dashboard.html", page


def test_a_dark_report_page_is_dark_and_its_hover_box_too(
    tmp_path, monkeypatch, playwright_browser
):
    """A's page, generated dark: the page's grounds and text, the plot's
    ground, grid and labels, and the hover box under a real mouse — fill,
    border and text as computed, with the trace's name in it."""
    _, report = _generate(tmp_path, monkeypatch, "dark")
    page = playwright_browser.new_page(viewport=VIEWPORT)
    problems: list[str] = []
    page.on("pageerror", lambda exc: problems.append(str(exc)))
    page.goto(report.as_uri())
    page.wait_for_selector("#plot-0 .scatterlayer")
    grounds = page.evaluate(
        """() => ({
          scheme: getComputedStyle(document.documentElement).colorScheme,
          page: getComputedStyle(document.body).backgroundColor,
          text: getComputedStyle(document.body).color,
          card: getComputedStyle(document.querySelector('.variable-section'))
                  .backgroundColor,
        })"""
    )
    assert grounds == {
        "scheme": "dark",
        "page": rgb(DARK["page"]),
        "text": rgb(DARK["text"]),
        "card": rgb(DARK["surface"]),
    }
    plot = page.locator("#plot-0")
    plot.evaluate("gd => gd.scrollIntoView({block: 'center'})")
    page.wait_for_timeout(200)
    assert_dark_plot(plot.evaluate(PLOT_GROUND))
    x, y = page.evaluate(POINT_PIXEL, [plot.element_handle(), 0.6])
    page.mouse.move(x - 40, y - 20)
    page.mouse.move(x, y, steps=4)
    page.wait_for_timeout(300)
    box = plot.evaluate(HOVER_BOX)
    page.close()
    assert_dark_hover(box, "Actual")
    assert problems == []


